// Copies build-time assets into app/: the Tabler icon subset (MIT) and the plate font (OFL).
// Usage: node tools/build-assets.mjs
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync } from 'node:fs';

const ICON_NAMES = [
  'camera', 'camera-plus', 'search', 'copy', 'phone', 'brand-whatsapp', 'plus', 'check', 'x',
  'chevron-left', 'chevron-right', 'chevron-down', 'trash', 'share', 'settings', 'chart-bar',
  'folders', 'pencil', 'photo', 'refresh', 'cloud', 'cloud-off', 'cloud-check', 'alert-triangle',
  'file-text', 'license', 'id', 'car', 'file-spreadsheet', 'download', 'upload', 'key', 'star',
  'loader-2', 'clipboard', 'circle-check', 'dots', 'receipt', 'calendar', 'user',
];

const dir = 'node_modules/@tabler/icons/icons/outline';
const icons = {};
for (const name of ICON_NAMES) {
  const file = `${dir}/${name}.svg`;
  if (!existsSync(file)) {
    console.warn('missing icon', name);
    continue;
  }
  icons[name] = readFileSync(file, 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*\/>/, '')
    .replace(/\s+/g, ' ')
    .trim();
}
writeFileSync(
  'app/js/ui/icons.js',
  `// Tabler Icons outline subset (MIT, tabler.io). Generated by tools/build-assets.mjs.\nexport const ICONS = ${JSON.stringify(icons, null, 1)};\n`,
);

mkdirSync('app/fonts', { recursive: true });
for (const subset of ['latin', 'latin-ext']) {
  const name = `barlow-condensed-${subset}-600-normal.woff2`;
  copyFileSync(`node_modules/@fontsource/barlow-condensed/files/${name}`, `app/fonts/${name}`);
}
console.log('icons', Object.keys(icons).length, 'fonts copied');
